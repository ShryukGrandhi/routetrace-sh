# shellcheck shell=bash
# Hop-by-hop packet forwarding through a loaded topology.
# Requires lib/topo.sh and everything it requires.
#
# At each router: inbound ACL -> local delivery check -> TTL decrement ->
# longest-prefix match -> recursive next-hop resolution -> outbound ACL ->
# hand-off to the device that owns the next-hop address on that segment.

TRACE_TTL=${TRACE_TTL:-64}

_trace_out() { ((TRACE_QUIET)) || printf '%s\n' "$*"; }

_trace_end() {
  TRACE_RESULT=$1
  TRACE_REASON=$2
  _trace_out "RESULT $1 $2 (hops: $TRACE_HOPS)"
  [[ $1 == DELIVERED ]]
}

# _trace_acl IFACE DIR ACL_ID -> returns 1 (and records the drop) on deny
_trace_acl() {
  (($3 >= 0)) || return 0
  acl_eval "$3" "$_PROTO" "$_SRC" "$_DST" "$_SPORT" "$_DPORT" "$_EST"
  local where="${ACL_NAME[$3]} $2 on ${IF_NAME[$1]}"
  if [[ $REPLY == deny ]]; then
    if ((ACL_HIT < 0)); then
      _HOP+="  acl $where: implicit deny"
    else
      _HOP+="  acl $where: '${ACE_TEXT[ACL_HIT]}'"
    fi
    return 1
  fi
  return 0
}

# trace_packet SRC DST PROTO SPORT DPORT ESTABLISHED [START_ROUTER]
# Prints one line per hop and a final "RESULT ..." line (unless TRACE_QUIET=1).
# Sets TRACE_RESULT (DELIVERED|DROPPED), TRACE_REASON, TRACE_HOPS.
# Returns 0 if delivered, 1 if dropped, 2 on bad input.
trace_packet() {
  local _SRC _DST _PROTO _SPORT=$4 _DPORT=$5 _EST=$6 _HOP
  local rid=-1 in_if=-1 i ttl=$TRACE_TTL r out own
  TRACE_HOPS=0 TRACE_RESULT="" TRACE_REASON=""
  ip_to_int "$1" || { echo "bad source address: $1" >&2; return 2; }
  _SRC=$REPLY
  ip_to_int "$2" || { echo "bad destination address: $2" >&2; return 2; }
  _DST=$REPLY
  proto_number "$3" || { echo "bad protocol: $3" >&2; return 2; }
  _PROTO=$REPLY

  # Locate the first-hop router: the owner of SRC, or the gateway of the
  # first segment (in load order) that contains SRC.
  own="_OWN_${_SRC}"
  if [[ -n ${7-} ]]; then
    topo_router_id "$7" || { echo "unknown router: $7" >&2; return 2; }
    rid=$REPLY
  fi
  if [[ -n ${!own-} && (rid -lt 0 || ${IF_RTR[${!own}]} -eq rid) ]]; then
    rid=${IF_RTR[${!own}]} # generated by the router itself
  else
    for ((i = 0; i < ${#IF_NAME[@]}; i++)); do
      [[ -n ${IF_ADDR[i]} && ${IF_UP[i]} == 1 ]] || continue
      ((rid < 0 || IF_RTR[i] == rid)) || continue
      if cidr_contains $((IF_ADDR[i] & MASK[IF_LEN[i]])) "${IF_LEN[i]}" "$_SRC"; then
        rid=${IF_RTR[i]} in_if=$i
        break
      fi
    done
  fi
  ((rid >= 0)) || { echo "no router has a segment containing $1; use --from" >&2; return 2; }

  _trace_out "trace $3 $1:$4 -> $2:$5"
  while :; do
    TRACE_HOPS=$((TRACE_HOPS + 1))
    local in_name=local
    ((in_if >= 0)) && in_name=${IF_NAME[in_if]}
    printf -v _HOP '%2d  %-6s in %-10s' "$TRACE_HOPS" "${R_NAME[rid]}" "$in_name"

    if ((in_if >= 0)) && ! _trace_acl "$in_if" in "${IF_ACLIN_ID[in_if]}"; then
      _trace_out "$_HOP"
      _trace_end DROPPED "denied by ACL ${IF_ACLIN[in_if]} in on ${R_NAME[rid]} ${IF_NAME[in_if]}"
      return
    fi

    own="_OWN_${_DST}"
    if [[ -n ${!own-} && ${IF_RTR[${!own}]} == "$rid" ]]; then
      _trace_out "$_HOP  local ${IF_NAME[${!own}]}"
      _trace_end DELIVERED "to router ${R_NAME[rid]} ${IF_NAME[${!own}]}"
      return
    fi

    if ((in_if >= 0)); then
      ttl=$((ttl - 1))
      if ((ttl <= 0)); then
        _trace_out "$_HOP  ttl expired"
        _trace_end DROPPED "TTL exceeded at ${R_NAME[rid]} (routing loop?)"
        return
      fi
    fi

    if ! rib_lookup "$rid" "$_DST"; then
      _trace_out "$_HOP  no route"
      _trace_end DROPPED "no route to $2 on ${R_NAME[rid]}"
      return
    fi
    r=$REPLY
    topo_route_text "$r"
    _HOP+="  [$REPLY]"
    if ! rib_resolve "$rid" "$r" "$_DST"; then
      _trace_out "$_HOP"
      _trace_end DROPPED "next hop unresolvable on ${R_NAME[rid]}"
      return
    fi
    if [[ $RES_IF == "$NULL_IF" ]]; then
      _trace_out "$_HOP"
      _trace_end DROPPED "null route on ${R_NAME[rid]}"
      return
    fi
    out=$RES_IF
    int_to_ip "$RES_NH"
    _HOP+="  out ${IF_NAME[out]} -> $REPLY"

    if ! _trace_acl "$out" out "${IF_ACLOUT_ID[out]}"; then
      _trace_out "$_HOP"
      _trace_end DROPPED "denied by ACL ${IF_ACLOUT[out]} out on ${R_NAME[rid]} ${IF_NAME[out]}"
      return
    fi
    _trace_out "$_HOP"

    # Hand the packet to whoever owns the next-hop address on that segment.
    own="_OWN_${RES_NH}"
    if [[ -n ${!own-} ]] && ((IF_RTR[${!own}] != rid)) &&
      cidr_contains $((IF_ADDR[out] & MASK[IF_LEN[out]])) "${IF_LEN[out]}" "$RES_NH"; then
      in_if=${!own}
      rid=${IF_RTR[in_if]}
      continue
    fi
    if ((RES_NH == _DST)) &&
      cidr_contains $((IF_ADDR[out] & MASK[IF_LEN[out]])) "${IF_LEN[out]}" "$_DST"; then
      _trace_end DELIVERED "to host $2 via ${R_NAME[rid]} ${IF_NAME[out]}"
      return
    fi
    int_to_ip "$RES_NH"
    _trace_end DROPPED "next hop $REPLY not present on ${IF_NAME[out]} segment (ARP failure)"
    return
  done
}
